#!/usr/bin/env python3
"""Makes src/atrac9_tables.h from the tables of Prospero Themes' Shared/Atrac9Tables.cs (GPL-3.0, itself generated from
Blaze414's ps5-theme atrac9.js, which follows LibAtrac9 by Alex Barney, MIT). Usage: gen_atrac9_tables.py Atrac9Tables.cs > src/atrac9_tables.h"""
import re, sys

src = open(sys.argv[1], encoding="utf-8").read()
item = re.compile(r'new\((\d+), (\d+), (\d+), (\d+), "([0-9a-f]+)", "([0-9a-f]+)"\)')

def section(name, nxt):
    a = src.index(name)
    return src[a:src.index(nxt, a)]

def books(text):
    """The entries of a one-dimensional book list: null or new(...)."""
    out = []
    for m in re.finditer(r'\bnull\b|new\(\d+, \d+, \d+, \d+, "[0-9a-f]+", "[0-9a-f]+"\)', text):
        t = m.group(0)
        out.append(None if t == "null" else tuple(item.match(t).groups()))
    return out

def entry(b):
    if b is None:
        return "{0,0,0,NULL,NULL}"
    vc, lg, vb, mb, bits, codes = b
    return '{%s,%s,%s,"%s","%s"}' % (vc, vb, mb, bits, codes)

sfu = books(section("public static readonly Atrac9Codebook?[] SfUnsigned", "public static readonly Atrac9Codebook?[] SfSigned").split("{", 1)[1])
sfs = books(section("public static readonly Atrac9Codebook?[] SfSigned", "/// <summary>Spectrum").split("{", 1)[1])
assert len(sfu) == 7 and len(sfs) == 6, (len(sfu), len(sfs))

body = section("var spec = new BookSpec?[][][]", "var result = new Atrac9Codebook?[spec.Length][][];")
body = body.split("\n", 1)[1]
sets, cur_set, cur_grp = [], None, None
pos = 0
# walk the text: "new BookSpec?[][]" starts a set, "new BookSpec?[] {" starts a group, the group ends at the closing "}"
for m in re.finditer(r'new BookSpec\?\[\]\[\]|new BookSpec\?\[\] \{(.*?)\}(?=,|\s*\})', body, re.S):
    if m.group(0) == "new BookSpec?[][]":
        sets.append([])
    else:
        sets[-1].append(books(m.group(1)))
assert len(sets) == 2 and all(len(s) == 8 for s in sets), [len(s) for s in sets]
assert all(len(g) == 4 for s in sets for g in s)

def arr(name):
    m = re.search(r'public static readonly (?:int|double)\[\] %s = \{([^}]*)\};' % name, src)
    return m.group(1).strip()

def arr2(name):
    m = re.search(r'public static readonly (?:int|double)\[\]\[\] %s =\s*\{(.*?)\}\s*;' % name, src, re.S)
    return [[x.strip() for x in g.split(",") if x.strip()] for g in re.findall(r'\{([^{}]*)\}', m.group(1))]

o = []
o.append("/* Generated by tools/gen_atrac9_tables.py from the tables of Prospero Themes (GPL-3.0), which follow Blaze414's ps5-theme\n * (GPL-3.0-or-later) and LibAtrac9 (MIT, (c) 2018 Alex Barney). Do not edit. */")
o.append("#pragma once\n#include <stddef.h>\n#include <stdint.h>\n")
o.append("typedef struct { uint8_t count, vbits, maxbits; const char *bits, *codes; } at9_book_spec_t;\n")
o.append("static const at9_book_spec_t k_at9_sfu[7] = {%s};" % ",".join(entry(b) for b in sfu))
o.append("static const at9_book_spec_t k_at9_sfs[6] = {%s};" % ",".join(entry(b) for b in sfs))
o.append("static const at9_book_spec_t k_at9_spec[2][8][4] = {")
for s in sets:
    o.append(" {")
    for g in s:
        o.append("  {%s}," % ",".join(entry(b) for b in g))
    o.append(" },")
o.append("};")
o.append("static const int k_at9_rates[16] = {%s};" % arr("SampleRates"))
o.append("static const int k_at9_power[16] = {%s};" % arr("FramePower"))
o.append("static const int k_at9_maxbands[16] = {%s};" % arr("MaxBands"))
o.append("static const int k_at9_bandunits[19] = {%s};" % arr("BandUnits"))
o.append("static const int k_at9_unitstart[31] = {%s};" % arr("UnitStart"))
o.append("static const int k_at9_unitbook[30] = {%s};" % arr("UnitBook"))
w = arr2("SfWeights")
assert len(w) == 8 and all(len(x) == 32 for x in w)
o.append("static const int k_at9_sfweights[8][32] = {%s};" % ",".join("{%s}" % ",".join(x) for x in w))
o.append("static const double k_at9_step[16] = {%s};" % arr("Step"))
o.append("static const double k_at9_stepfine[16] = {%s};" % arr("StepFine"))
o.append("static const int k_at9_basecurve[48] = {%s};" % arr("BaseCurve"))
g = arr2("BexGroups")
o.append("static const int k_at9_bexgroups[%d][3] = {%s};" % (len(g), ",".join("{%s}" % ",".join(x) for x in g)))
c = arr2("BexCounts")
o.append("static const int k_at9_bexcounts[5][6] = {%s};" % ",".join("{%s}" % ",".join(x) for x in c))
# BexLengths is three levels deep: [mode][band] -> list
m = re.search(r'BexLengths =\s*\{(.*?)\n    \};', src, re.S)
modes = []
for line in m.group(1).splitlines():
    if "new int[][]" not in line:
        continue
    bands = [[x.strip() for x in b.split(",") if x.strip()] for b in re.findall(r'new int\[\] \{([^}]*)\}', line)]
    assert len(bands) == 6, len(bands)
    modes.append(bands)
assert len(modes) == 5
o.append("static const int k_at9_bexlens[5][6][4] = {%s};" % ",".join("{%s}" % ",".join("{%s}" % ",".join((b + ['0'] * 4)[:4]) for b in md) for md in modes))
print("\n".join(o))
